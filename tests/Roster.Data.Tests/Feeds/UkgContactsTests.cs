// Port of src/lib/csv/ukgContacts.test.ts. The preamble's export name is neutral text here.

using Roster.Data.Feeds;

namespace Roster.Data.Tests.Feeds;

public class UkgContactsTests
{
    // Mirrors the real export's structure: metadata preamble, blank line, header
    // row, then quoted "prefix-surname, firstname" names with D/MM/YYYY dates.
    private const string Sample = """
        Export Name:,Contact Details - Export,,,,,,,,,,
        Generated By:,Test User,,,,,,,,,,
        Time Period:,Current Pay Period,,,,,,,,,,
        Location:,501000 Test Store,,,,,,,,,,
        Sorted By:,Location Ascending; Employee Name Ascending,,,,,,,,,,
        Filtered By:,Location(Is Not Null ),,,,,,,,,,
        Total Rows:,6,,,,,,,,,,
        Currency:,NONE,,,,,,,,,,
        ,,,,,,,,,,,
        StoreID,Location,Employee Name,Employee ID,Job,Contract Hrs,Notional Hrs,Phone Number,Mobile Number,Birth Date,Hire Date,Probation End Date
        G999,501000,"1-Manager, Morgan A",100001,ST MANAGER,90,9,,,12/06/1991,21/11/2016,19/02/2017
        G999,501000,"2-Second, Sam L",100002,ST ASSIST MANAGER,80,8,,,14/09/1996,4/12/2023,3/03/2024
        G999,501000,"3-Duty, Dana A",100003,ST DUTY STORE MANAGER,70,7.5,,,23/02/1985,4/12/2017,6/03/2017
        G999,501000,"5L-Limited, Lee J",100004,ST ASSIST,21,5.5,,,22/12/2005,8/04/2024,7/07/2024
        G999,501000,"6C-Junior, Jamie T",100005,ST ASSIST JNR CASUAL,0,0,,,11/05/2009,1/06/2026,30/08/2026
        G999,501000,"4-Assist, Alex D",100006,ST ASSIST,60,6.5,,,15/09/1972,8/12/2014,6/03/2015

        """;

    private static readonly HashSet<string> Codes = ["G999"];
    private static readonly DateOnly AsOf = new(2026, 8, 13);

    [Fact]
    public void Strips_the_preamble_and_parses_every_data_row()
    {
        var res = UkgContacts.ValidateContacts(Sample, Codes);
        Assert.Empty(res.FileErrors);
        Assert.Empty(res.Errors);
        Assert.Equal(6, res.ValidRows.Count);
    }

    [Fact]
    public void Keeps_the_UKG_name_format_verbatim_and_maps_jobs_to_roles()
    {
        var byId = UkgContacts.ValidateContacts(Sample, Codes).ValidRows.ToDictionary(r => r.UkgEmployeeId);
        Assert.Equal(("1-Manager, Morgan A", "SM"), (byId["100001"].Name, byId["100001"].Role));
        Assert.Equal(("2-Second, Sam L", "ASM"), (byId["100002"].Name, byId["100002"].Role));
        Assert.Equal(("3-Duty, Dana A", "DSM"), (byId["100003"].Name, byId["100003"].Role));
        Assert.Equal(("5L-Limited, Lee J", "SA"), (byId["100004"].Name, byId["100004"].Role));
        Assert.Equal(("6C-Junior, Jamie T", "JSA"), (byId["100005"].Name, byId["100005"].Role));
    }

    [Fact]
    public void Carries_contracts_as_FORTNIGHTLY_hours_and_converts_D_MM_YYYY_dates()
    {
        var rows = UkgContacts.ValidateContacts(Sample, Codes).ValidRows;
        var sm = rows.First(r => r.UkgEmployeeId == "100001");
        Assert.Equal(90, sm.ContractHours);
        Assert.Equal(9, sm.NotionalHours);
        Assert.Equal(new DateOnly(2016, 11, 21), sm.HireDate);
        Assert.Equal(new DateOnly(1991, 6, 12), sm.BirthDate);
        // Single-digit day: "4/12/2023" is 4 December, not 12 April.
        Assert.Equal(new DateOnly(2023, 12, 4), rows.First(r => r.UkgEmployeeId == "100002").HireDate);
    }

    [Fact]
    public void Rejects_unknown_stores_and_rows_without_a_hire_date_row_by_row()
    {
        var bad = Sample.Replace("G999,501000,\"4-Assist", "G111,501000,\"4-Assist").Replace(",8/04/2024,7/07/2024", ",,7/07/2024");
        var res = UkgContacts.ValidateContacts(bad, Codes);
        Assert.Equal(4, res.ValidRows.Count);
        Assert.Equal(2, res.Errors.Count);
        Assert.Equal(["Hire Date", "StoreID"], res.Errors.Select(e => e.Field!).Order(StringComparer.Ordinal));
    }

    [Fact]
    public void Fails_loudly_on_a_file_without_the_contacts_header_row()
    {
        var res = UkgContacts.ValidateContacts("Location,Employee Name\nX,Y\n", Codes);
        Assert.True(res.FileErrors.Count + res.Errors.Count > 0);
        Assert.Empty(res.ValidRows);
    }

    [Fact]
    public void Orders_the_job_keywords_so_composites_resolve_correctly()
    {
        Assert.Equal("ASM", UkgContacts.RoleFromJob("ST ASSIST MANAGER"));
        Assert.Equal("DSM", UkgContacts.RoleFromJob("ST DUTY STORE MANAGER"));
        Assert.Equal("SM", UkgContacts.RoleFromJob("ST MANAGER"));
        Assert.Equal("JSA", UkgContacts.RoleFromJob("ST ASSIST JNR CASUAL"));
        Assert.Equal("SA", UkgContacts.RoleFromJob("ST ASSIST"));
        Assert.Null(UkgContacts.RoleFromJob(""));
    }

    [Fact]
    public void Falls_back_to_the_name_rank_prefix()
    {
        Assert.Equal("SM", UkgContacts.RoleFromNamePrefix("1-Smith, Jo"));
        Assert.Equal("ASM", UkgContacts.RoleFromNamePrefix("2-Smith, Jo"));
        Assert.Equal("DSM", UkgContacts.RoleFromNamePrefix("3-Smith, Jo"));
        Assert.Equal("SA", UkgContacts.RoleFromNamePrefix("5L-Smith, Jo"));
        Assert.Equal("JSA", UkgContacts.RoleFromNamePrefix("6C-Smith, Jo"));
    }

    [Fact]
    public void Picks_the_manager_band_nearest_the_fortnightly_contract_at_year_1()
    {
        Assert.Equal("SM-45-1", UkgContacts.PositionForImport("SM", 90, null, AsOf));
        Assert.Equal("SM-50-1", UkgContacts.PositionForImport("SM", 100, null, AsOf));
        Assert.Equal("ASM-40-1", UkgContacts.PositionForImport("ASM", 80, null, AsOf));
        Assert.Equal("ASM-30-1", UkgContacts.PositionForImport("ASM", 60, null, AsOf));
        Assert.Equal("DSM", UkgContacts.PositionForImport("DSM", 70, null, AsOf));
        Assert.Equal("SA-FF", UkgContacts.PositionForImport("SA", 60, null, AsOf));
    }

    [Fact]
    public void Splits_JSAs_16_17_on_their_birth_date_defaulting_to_16_when_unknown()
    {
        Assert.Equal("JSA-17", UkgContacts.PositionForImport("JSA", 0, new DateOnly(2009, 5, 11), AsOf));
        Assert.Equal("JSA-16", UkgContacts.PositionForImport("JSA", 0, new DateOnly(2009, 11, 6), AsOf)); // turns 17 in Nov
        Assert.Equal("JSA-16", UkgContacts.PositionForImport("JSA", 0, null, AsOf));
    }
}
